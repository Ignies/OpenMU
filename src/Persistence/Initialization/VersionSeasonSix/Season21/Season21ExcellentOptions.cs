namespace MUnique.OpenMU.Persistence.Initialization.VersionSeasonSix.Season21;

/// <summary>
/// The excellent options which a piece of jewelry of Season 21 takes: the ones of a Season 6 ring or pendant.
/// </summary>
internal enum Season21ExcellentOptions
{
    /// <summary>
    /// No excellent options.
    /// </summary>
    None,

    /// <summary>
    /// The defensive options of the rings.
    /// </summary>
    Defense,

    /// <summary>
    /// The physical attack options of the pendants.
    /// </summary>
    Damage,

    /// <summary>
    /// The wizardry attack options of the pendants.
    /// </summary>
    Wizardry,
}
